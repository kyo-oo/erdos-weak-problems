def col_masks(p, o2, o3, h):
    """per (k mod o2) bitmask over l mod L: cells with 2^k 3^l = t.
    Built for a GIVEN target t; we build ALL cosets: per k-class the l-set
    is a coset of <3> structure — we precompute per k the l-pattern mod o3,
    then tile it (L/o3) times into an L-bit int."""
    # l-patterns: for each residue class of 3^l, precompute map value->l mod o3
    p3 = {}
    v = 1
    for l in range(o3):
        p3.setdefault(v, l)
        v = v * 3 % p
    # per k mod o2: the needed 3^l values = t * 2^{-k} must lie in t*<2>^-1...
    # we build per-k mask for a target t at anneal time; here we build the
    # machinery: per k mod o2, the set of achievable 2^k (list), and a helper
    pows2 = {}
    v = 1
    for k in range(o2):
        pows2.setdefault(v, []).append(k)
        v = v * 2 % p
    # tile helper
    def tile(bits_o3):
        m = 0
        for l in bits_o3:
            m |= 1 << l
        full = 0
        rep = L // o3
        for r in range(rep):
            full |= m << (r * o3)
        return full
    return pows2, p3, tile

def build_masks_for_target(p, o2, o3, t, pows2, p3, tile):
    """column bitmasks for target class t: dict k_mod_o2 -> L-bit int."""
    inv2t = {}
    masks = {}
    for val2, ks in pows2.items():
        need = t * pow(val2, -1, p) % p
        if need in p3:
            bits = [p3[need] + s * o3 for s in range(L // o3)]
            m = 0
            for l in bits:
                m |= 1 << l
            for k in ks:
                masks[k] = m
    return masks

