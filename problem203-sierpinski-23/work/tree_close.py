"""THE SPLIT-TREE COVERING SEARCH for Erdos #203 (closes the covering symbolically).

Region R(a, nu, b, nu') = {(k, l): k = a mod nu, l = b mod nu'}.
Prime q (h, U, V, W): coset C(q,W) = {(k,l): U*k + V*l = W mod h}.
ABSORPTION: R <= C(q,W) iff gcd(h, U*nu, V*nu') == h and W = U*a + V*b mod h.
   (image of U*k + V*l over R = Ua + Vb + <U*nu, V*nu'> mod h; single point
   iff the subgroup generated by U*nu, V*nu' together with h is trivial mod h.)
SPLIT: refine nu (or nu') by multiplying with a CRT prime factor of L.
ROOT: R(0, 1, 0, 1) = Z^2.
GOAL: every leaf absorbed by some palette prime -> covering closed.
Palette: pal_dlog_full.json entries [q, h, U, V, o2, o3].
Then: CRT m (m = -(g^W)^-1 mod q per leaf prime... need distinct primes!),
m = 1 mod 6, m > max q; verify spot checks.
"""
import json, math, time, random
from math import gcd
from collections import deque

L = 27720  # torus modulus; L = 2^3 * 3^2 * 5 * 7 * 11
pal = json.load(open("../pal_dlog_full.json"))
pal = [(int(r[0]), int(r[1]), int(r[2]), int(r[3])) for r in pal]
pal = [r for r in pal if L % r[1] == 0]  # h | L needed for periodicity
# distinct prime bases (CRT coprimality)
bases = {}
for (q, h, U, V) in pal:
    p = q
    for d in range(2, int(q**0.5) + 1):
        if q % d == 0:
            p = d
            break
    if p not in bases or 1.0 / h > 1.0 / bases[p][1]:
        bases[p] = (q, h, U, V)
pal = sorted(bases.values(), key=lambda r: -1.0 / r[1])
print(f"palette (distinct bases, h|{L}): {len(pal)}, budget {sum(1.0/r[1] for r in pal):.4f}")

CRT_PRIMES = [(2, 3), (3, 2), (5, 1), (7, 1), (11, 1)]  # prime-power split of L

def absorb_prime(a, nu, b, nup, q, h, U, V):
    """return W if R(a,nu,b,nup) <= coset(q,W), else None"""
    g = gcd(gcd(h, U * nu), V * nup)
    # careful: subgroup generated by U*nu and V*nup mod h: gcd(U*nu, V*nup, h)
    if g != h:
        return None
    # need U*nu and V*nup BOTH = 0 mod h? NO: the subgroup <U*nu, V*nup> mod h
    # is generated; single point iff U*nu = 0 mod h and V*nup = 0 mod h
    # (each axis alone must be constant). Actually U*k over k=a+nu*t varies
    # by U*nu per step: constant iff h | U*nu. Same for V.
    return None

def absorbs(a, nu, b, nup, q, h, U, V):
    """R <= coset(q, W): need h | U*nu AND h | V*nup; W = (U*a + V*b) mod h"""
    if (U * nu) % h != 0 or (V * nup) % h != 0:
        return None
    return (U * a + V * b) % h

def try_absorb(region, allowed):
    """find (prime_idx, W) absorbing the region; prefer largest 1/h? any."""
    a, nu, b, nup = region
    for i in allowed:
        q, h, U, V = pal[i]
        W = absorbs(a, nu, b, nup, q, h, U, V)
        if W is not None:
            return i, W
    return None

def split(region):
    """split region by a CRT prime on the axis that keeps nu small; yield children"""
    a, nu, b, nup = region
    children = []
    for (p, e) in CRT_PRIMES:
        if nu * p <= L and (nu * p) % 1 == 0:
            if nu * p <= L:
                # split k-axis by p
                for j in range(p):
                    children.append(((a + j * nu) % (nu * p), nu * p, b, nup))
                return children
        if nup * p <= L:
            for j in range(p):
                children.append((a, nu, (b + j * nup) % (nup * p), nup * p))
            return children
    return children

# THE SEARCH: BFS with absorption; nodes = regions; track used primes
# (a prime can serve MULTIPLE leaves with DIFFERENT W only if... NO: one W
# per prime (m mod q fixed). So a prime absorbs many leaves only at the SAME
# W. Track per-prime W once assigned.)
t0 = time.time()
leaves = []          # (region, prime_idx, W)
fixed = {}           # prime_idx -> W
queue = deque([(0, 1, 0, 1)])
n_nodes = 0
# order: try to absorb with already-fixed primes first (same W), then new
while queue:
    reg = queue.popleft()
    n_nodes += 1
    a, nu, b, nup = reg
    # 1) already-fixed primes
    hit = None
    for i, W in fixed.items():
        q, h, U, V = pal[i]
        W2 = absorbs(a, nu, b, nup, q, h, U, V)
        if W2 is not None and W2 == W:
            hit = (i, W)
            break
    if hit:
        leaves.append((reg, hit[0], hit[1]))
        continue
    # 2) new prime absorption: prefer the prime with the largest h
    #    (smallest 1/h = least budget burn)? Prefer ANY that absorbs whole.
    best = None
    for i in range(len(pal)):
        if i in fixed:
            continue
        q, h, U, V = pal[i]
        W = absorbs(a, nu, b, nup, q, h, U, V)
        if W is not None:
            best = (i, W)
            break
    if best:
        fixed[best[0]] = best[1]
        leaves.append((reg, best[0], best[1]))
        continue
    # 3) split
    ch = split(reg)
    if not ch:
        print(f"DEAD END at region {reg} -- cannot split or absorb")
        leaves.append((reg, -1, -1))
        break
    queue.extend(ch)

print(f"nodes={n_nodes}, leaves={len(leaves)}, fixed primes={len(fixed)} ({time.time()-t0:.1f}s)")
uncovered = [lf for lf in leaves if lf[1] < 0]
print(f"uncovered leaves: {len(uncovered)}")

# ===== CRT m =====
# For each fixed prime q with W: m = -(g^W)^{-1} mod q where g = the
# dlog generator. We don't have g stored; instead: m*2^k*3^l = -1 mod q on
# the coset means 2^k 3^l = g^{Uk+Vl} = g^W, so m = -(g^W)^{-1}.
# Recover g from (q,h,U,V): g = 2^{h/U'}... easier: find g by search: the
# subgroup generator g with g^U = 2 and g^V = 3 mod q.
def find_g(q, h, U, V):
    for x in range(2, q):
        if pow(x, U, q) == 2 % q and pow(x, V, q) == 3 % q:
            return x
    return None

# verify leaves + build m
ok = True
ms = []
for i, W in fixed.items():
    q, h, U, V = pal[i]
    g = find_g(q, h, U, V)
    if g is None:
        print(f"NO g for q={q}")
        ok = False
        continue
    gw = pow(g, W, q)
    minv = pow(-gw, -1, q)
    ms.append((q, minv))
    print(f"prime q={q:6d} h={h:5d} W={W:5d} -> m = {minv} mod {q}")

json.dump({"L": L, "pal": pal, "fixed": {str(k): v for k, v in fixed.items()},
           "leaves": [[list(r), i, w] for (r, i, w) in leaves]},
          open("tree_cert.json", "w"))
print("wrote tree_cert.json")
