#!/usr/bin/env python3
"""
chain203.py — W63-B3: THE CHAIN-PLANNER (stage 1: the alignment census).

THE LAW (this round's derivation, campaign-internal):
A covering of the (k,l)-torus by prime cosets C_q = {(k,l): chi_q(k,l) = w_q}
with chi_q(k,l) = U_q k + V_q l mod h_q (h_q = |<2,3>_q|, U,V = dlogs) reduces
to a 1D covering IFF all primes factor through ONE master character
chi*(k,l) = A k + B l mod h*:  Lambda_q = ker chi_q ⊇ ker chi* (chi* = rho∘chi_q)
  <=> h_q | h*  and  (U_q,V_q) ≡ c·(A,B) (mod h_q) with c a UNIT mod h_q.
Then C_q = chi*^{-1}(ONE class mod h_q) and the FULL 2D problem becomes the
CLASSIC 1D covering of Z/h* by one residue class per prime.  This is the
lattice-CHAIN structure of the S043 alignment law, made exact.

Pairwise-disjointness law: two cosets C_i, C_j are disjoint only if the joint
character (chi_i, chi_j): Z² -> Z/h_i x Z/h_j is NON-surjective ("aligned");
transverse pairs (|image| = h_i·h_j) ALWAYS intersect.

Stage 1 (this file): the palette census:
  (a) validate all dlog rows (gcd structure + full re-derivation on a sample),
  (b) h-histogram (the 1D moduli inventory),
  (c) pairwise alignment matrix over the strong small-h primes,
  (d) master-family scan: for every master character that is a palette prime's
      own character (and small h*-multiples), the aligned family + budget,
  (e) Egyptian-1 subset census over master families (the dissection lane).
Output: chain203_census.json + console report.
"""
import json, math, os, sys, time
from collections import defaultdict, Counter

HERE = os.path.dirname(os.path.abspath(__file__))
DL = os.path.join(HERE, "pal_dlog_full.json")

def log(s): print(s, flush=True)

def factor_small(x):
    fs = set(); d = 2
    while d * d <= x:
        while x % d == 0: fs.add(d); x //= d
        d += 1 if d == 2 else 2
    if x > 1: fs.add(x)
    return fs

def units_mod(h):
    return [c for c in range(1, h) if math.gcd(c, h) == 1] + ([1] if h == 1 else [])

def order_of(a, p):
    n = p - 1
    o = n
    for q in factor_small(n):
        while o % q == 0 and pow(a, o // q, p) == 1: o //= q
    return o

def validate_row(p, h, U, V, o2, o3):
    """necessary conditions on a dlog row (no g needed)."""
    if h % o2 or h % o3: return "h-lcm"
    if h // math.gcd(U, h) != o2: return "U-order"
    if h // math.gcd(V, h) != o3: return "V-order"
    if math.gcd(U, math.gcd(V, h)) != 1: return "gen"   # <U,V> must span Z/h
    return None

def recompute_dlog(p):
    """full independent re-derivation: generator of <2,3>_q + BSGS dlogs."""
    o2 = order_of(2, p); o3 = order_of(3, p)
    h = o2 * o3 // math.gcd(o2, o3)
    # BFS the subgroup <2,3>
    sub = {1}
    frontier = [1]
    while frontier:
        nf = []
        for v in frontier:
            for m in (2, 3):
                w = v * m % p
                if w not in sub: sub.add(w); nf.append(w)
        frontier = nf
    if len(sub) != h: return None
    fs = factor_small(h)
    for g in sorted(sub):
        if g == 1: continue
        o = h
        for q in fs:
            while o % q == 0 and pow(g, o // q, p) == 1: o //= q
        if o == h:
            # BSGS dlogs of 2, 3
            m = int(math.isqrt(h)) + 1
            table = {}; cur = 1
            for j in range(m):
                if cur not in table: table[cur] = j
                cur = cur * g % p
            ginv_m = pow(pow(g, m, p), -1, p)
            def bsgs(t):
                gamma = t % p
                for i in range(m + 2):
                    j = table.get(gamma)
                    if j is not None: return (i * m + j) % h
                    gamma = gamma * ginv_m % p
                return None
            U = bsgs(2); V = bsgs(3)
            if U is not None and V is not None:
                assert pow(g, U, p) == 2 % p and pow(g, V, p) == 3 % p
                return (h, U, V, o2, o3)
    return None

def aligned_to_master(U, V, h, A, B, hstar):
    """(U,V) ≡ c(A,B) mod h for a unit c, and h | hstar."""
    if hstar % h: return None
    for c in units_mod(h):
        if (c * A - U) % h == 0 and (c * B - V) % h == 0:
            return c
    return None

def pair_joint_index(U1, V1, h1, U2, V2, h2):
    """|image| of Z² -> Z/h1 x Z/h2, (k,l) -> (U1k+V1l, U2k+V2l), via per-p CRT.
    Returns (|S|, cyclic_quotient_flag) where |S| = [Z²:Λ1∩Λ2]."""
    # per prime power: S_p <= Z/p^a x Z/p^b generated by (U1,U2),(V1,V2)
    total = 1
    for p in factor_small(h1 * h2):
        a = 0; t = h1
        while t % p == 0: t //= p; a += 1
        b = 0; t = h2
        while t % p == 0: t //= p; b += 1
        if a == 0 and b == 0: continue
        pa, pb = p ** a, p ** b
        # BFS over Z/p^a x Z/p^b generated by the two columns
        cols = ((U1 % pa, U2 % pb), (V1 % pa, V2 % pb))
        seen = {(0, 0)}
        frontier = [(0, 0)]
        while frontier:
            nf = []
            for s in frontier:
                for c in cols:
                    ns = ((s[0] + c[0]) % pa, (s[1] + c[1]) % pb)
                    if ns not in seen: seen.add(ns); nf.append(ns)
            frontier = nf
        total *= len(seen)
    return total

def main():
    t0 = time.time()
    rows = json.load(open(DL))
    log(f"[load] {len(rows)} dlog rows")
    # (a) validation
    bad = []
    for r in rows:
        p, h, U, V, o2, o3 = r
        if validate_row(p, h, U, V, o2, o3) is not None: bad.append(r)
    log(f"[validate] {len(bad)} rows fail the gcd-structure check; sample re-derivation:")
    rng = __import__("random").Random(203)
    sample = rng.sample(rows, 12)
    ok = 0
    for (p, h, U, V, o2, o3) in sample:
        rd = recompute_dlog(p)
        if rd is None: log(f"  p={p}: RE-DERIVATION FAILED"); continue
        h2, U2, V2, o22, o32 = rd
        # consistency: exists unit t with (U2,V2)=t(U,V) OR (U,V)=t(U2,V2)
        match = any((t * U - U2) % h == 0 and (t * V - V2) % h == 0
                    for t in units_mod(h))
        log(f"  p={p}: h={h}/{h2} o2={o2}/{o22} o3={o3}/{o32} dlog-match={match}")
        ok += bool(match and h == h2 and o2 == o22 and o3 == o32)
    log(f"[validate] dual-method dlog agreement: {ok}/{len(sample)}")

    # (b) h-histogram
    hist = Counter(r[1] for r in rows)
    budget = sum(1.0 / h for h in hist.elements())
    log(f"[hist] total palette budget = {budget:.4f} over {len(rows)} primes")
    log("[hist] h : count (h <= 120): " + ", ".join(f"{h}:{hist[h]}" for h in sorted(hist) if h <= 120))

    # small-h inventory with multiplicities and per-h direction spread
    small = [r for r in rows if r[1] <= 120]
    log(f"[small] {len(small)} primes with h <= 120; budget {sum(1.0/r[1] for r in small):.4f}")

    # (c) pairwise alignment on the strong core (h <= 60)
    core = [r for r in rows if r[1] <= 60]
    log(f"[core] {len(core)} primes with h <= 60 (the chain-lane core):")
    for r in core: log(f"   p={r[0]:6d} h={r[1]:3d} U={r[2]:5d} V={r[3]:5d} o2={r[4]:3d} o3={r[5]:3d}")
    n = len(core)
    align_pairs = []
    for i in range(n):
        p1, h1, U1, V1 = core[i][0], core[i][1], core[i][2], core[i][3]
        for j in range(i + 1, n):
            p2, h2, U2, V2 = core[j][0], core[j][1], core[j][2], core[j][3]
            S = pair_joint_index(U1, V1, h1, U2, V2, h2)
            if S < h1 * h2:
                align_pairs.append((p1, p2, h1, h2, S, h1 * h2))
    log(f"[pairs] aligned (non-transverse) pairs among h<=60 core: {len(align_pairs)}")
    for (p1, p2, h1, h2, S, full) in align_pairs[:60]:
        log(f"   {p1}-{p2}: |S|={S} < {full} (ratio {S/full:.4f})")

    # (d) master-family scan: master = each core prime's own character,
    #     family = primes aligned to it (h_q | h*, direction unit-proportional)
    fams = []
    for (p0, h0, U0, V0, o20, o30) in core:
        for mult in (1, 2, 3, 4, 6, 8, 12):
            hstar = h0 * mult
            fam = []
            for r in rows:
                p, h, U, V = r[0], r[1], r[2], r[3]
                if aligned_to_master(U, V, h, U0, V0, hstar) is not None:
                    fam.append(r)
            if fam:
                bud = sum(1.0 / r[1] for r in fam)
                fams.append((bud, p0, hstar, fam))
    fams.sort(key=lambda t: -t[0])
    log(f"[masters] {len(fams)} master families scanned; top by budget:")
    for (bud, p0, hstar, fam) in fams[:12]:
        log(f"   master p={p0} h*={hstar}: family={len(fam)} budget={bud:.4f} "
            f"h's={[r[1] for r in fam[:14]]}")

    out = {"rows": len(rows), "budget_total": budget,
           "hist": {str(h): hist[h] for h in sorted(hist) if h <= 200},
           "align_pairs": align_pairs,
           "masters": [[b, p0, hstar, [r[0] for r in fam]] for (b, p0, hstar, fam) in fams[:40]]}
    json.dump(out, open(os.path.join(HERE, "chain203_census.json"), "w"))
    log(f"[done] {time.time()-t0:.0f}s")

if __name__ == "__main__":
    main()
