#!/usr/bin/env python3
"""P203 census: palette of primes q>=5 with lattice data.

For each prime q: h = |<2,3>_q| (subgroup generated by 2,3 mod q), and
(U,V) with the covering congruence  U*k + V*l ≡ W (mod h)  <=>  q | m*2^k*3^l+1
(once m mod q is fixed via W). Lambda_q = {(k,l): Uk+Vl ≡ 0 mod h}, index h.

Method: SPF sieve, order computation, closure enumeration (cap), brute dlogs
for small h. Output: JSON palette sorted by 1/h.
"""
import json, sys, time
import numpy as np

T0 = time.time()
LIM = 2_000_000           # direct prime scan bound
ORD_CAP = 2520            # max ord_q(2), ord_q(3) to keep
H_FULL = 400              # compute (U,V) when h <= this
H_KEEP = 5000             # keep prime record when h <= this

# SPF sieve
spf = np.zeros(LIM + 1, dtype=np.int32)
for i in range(2, int(LIM**0.5) + 1):
    if spf[i] == 0:
        spf[i*i::i][spf[i*i::i] == 0] = i
spf[spf == 0] = np.arange(LIM + 1, dtype=np.int32)[spf == 0]
spf[0] = spf[1] = 1

def factorize(n):
    f = {}
    while n > 1:
        p = int(spf[n]); c = 0
        while n % p == 0: n //= p; c += 1
        f[p] = c
    return f

def n_order(a, p, fac):
    o = p - 1
    for f in fac:
        while o % f == 0 and pow(a, o // f, p) == 1:
            o //= f
    return o

def closure_order(p, cap):
    """|<2,3>| by BFS closure, capped."""
    S = {1}
    frontier = [1]
    while frontier:
        nf = []
        for x in frontier:
            for y in (x * 2 % p, x * 3 % p):
                if y not in S:
                    S.add(y)
                    if len(S) > cap: return None
                    nf.append(y)
        frontier = nf
    return len(S)

def find_uv(p, h, o2, o3):
    """generator gamma of <2,3> (order h), then U=dlog_gam(2), V=dlog_gam(3)."""
    # try gamma = 2^i 3^j
    fac_h = factorize(h)
    def order_of(g):
        o = h
        for f in fac_h:
            while o % f == 0 and pow(g, o // f, p) == 1:
                o //= f
        return o
    p2 = 1
    for i in range(o2):
        p3 = p2
        for j in range(o3):
            if (i or j) and order_of(p3) == h:
                gam = p3
                # brute dlogs
                U = V = None
                cur = 1
                for t in range(h):
                    if cur == 2: U = t
                    if cur == 3: V = t
                    if U is not None and V is not None: break
                    cur = cur * gam % p
                if U is not None and V is not None:
                    return U, V
            p3 = p3 * 3 % p
        p2 = p2 * 2 % p
    return None

def main():
    primes = [int(x) for x in np.nonzero((np.arange(LIM+1) >= 5) & (np.array([True]+[True]*LIM)))[0]]  # placeholder
    # simple prime list from spf
    pls = []
    is_p = (spf == np.arange(LIM+1, dtype=np.int32))
    for p in range(5, LIM):
        if is_p[p]: pls.append(p)
    print(f"primes 5..{LIM}: {len(pls)}", flush=True)
    pal = []
    for p in pls:
        fac = factorize(p - 1)
        o2 = n_order(2, p, fac)
        if o2 > ORD_CAP: continue
        o3 = n_order(3, p, fac)
        if o3 > ORD_CAP: continue
        if o2 * o3 > 4 * H_KEEP: continue
        h = closure_order(p, H_KEEP)
        if h is None or h < 4: continue
        rec = {"p": p, "h": h, "o2": o2, "o3": o3}
        if h <= H_FULL:
            uv = find_uv(p, h, o2, o3)
            if uv: rec["U"], rec["V"] = int(uv[0]), int(uv[1])
            else: rec["U"] = rec["V"] = None
        else:
            rec["U"] = rec["V"] = None
        pal.append(rec)
    pal.sort(key=lambda r: r["h"])
    bud = 0.0
    for r in pal:
        bud += 1.0 / r["h"]
        r["cum"] = round(bud, 6)
    print(f"palette size {len(pal)}, total budget {bud:.4f}", flush=True)
    with open(sys.argv[1] if len(sys.argv) > 1 else "palette.json", "w") as f:
        json.dump(pal, f)
    # report
    for r in pal[:80]:
        print(f"p={r['p']:>8} h={r['h']:>5} o2={r['o2']:>5} o3={r['o3']:>5} "
              f"U={r['U']} V={r['V']} cum={r['cum']}", flush=True)
    print(f"time {time.time()-T0:.1f}s", flush=True)

main()
